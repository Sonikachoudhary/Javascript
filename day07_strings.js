// Day 07 - JavaScript Strings

// Example 1: Creating a String
let name = "Sonika";
console.log("Name:", name);

// Example 2: String Length
let message = "Hello JavaScript";
console.log("Length:", message.length);

// Example 3: Convert to Uppercase
let text = "javascript";
console.log("Uppercase:", text.toUpperCase());

// Example 4: Convert to Lowercase
let subject = "PROGRAMMING";
console.log("Lowercase:", subject.toLowerCase());

// Example 5: Access Characters
let language = "JavaScript";
console.log("First character:", language[0]);
console.log("Third character:", language[2]);

// Example 6: Concatenation
let firstName = "Sonika";
let lastName = "Choudhary";

let fullName = firstName + " " + lastName;
console.log("Full Name:", fullName);

// Example 7: Check Whether a Word Exists
let sentence = "I am learning JavaScript";
console.log("Contains JavaScript:", sentence.includes("JavaScript"));